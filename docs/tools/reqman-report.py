def _find_matching_brace(text, start):
    """start is the index of an opening '{'; returns index of the match."""
    depth = 0
    i = start
    while i < len(text):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return i
        i += 1
    return len(text)


def _match_args(text, pos, nargs):
    """From pos, greedily match up to nargs consecutive {...} groups."""
    args = []
    i = pos
    for _ in range(nargs):
        while i < len(text) and text[i].isspace():
            i += 1
        if i >= len(text) or text[i] != "{":
            break
        end = _find_matching_brace(text, i)
        args.append(text[i + 1:end])
        i = end + 1
    return args, i


def _find_env_end(text, name, start):
    """start = index right after the opening \\begin{name}. Returns
    (content_end, after_end) for the matching \\end{name}, nesting-aware."""
    pattern = re.compile(
        r"\\begin\s*\{" + re.escape(name) + r"\}|"
        r"\\end\s*\{" + re.escape(name) + r"\}"
    )
    depth = 1
    pos = start
    while True:
        m = pattern.search(text, pos)
        if not m:
            return len(text), len(text)
        if m.group(0).startswith(r"\begin"):
            depth += 1
        else:
            depth -= 1
            if depth == 0:
                return m.start(), m.end()
        pos = m.end()


def _format_list(name, inner):
    items = list(_ITEM_RE.finditer(inner))
    if not items:
        return inner
    lines = []
    for idx, m in enumerate(items):
        label = m.group(1)
        start = m.end()
        end   = items[idx + 1].start() if idx + 1 < len(items) else len(inner)
        body  = _process_macros(inner[start:end].strip())
        bullet = f"{idx + 1}." if name == "enumerate" else "-"
        prefix = f"[{label}] " if label else ""
        lines.append(f"{bullet} {prefix}{body}")
    return "\n".join(lines) + "\n"


def _extract_environments(text):
    """Drop figure/center/tikzpicture envs; turn itemize/enumerate into
    plain lists; recurse into anything else and keep its inner content."""
    out = []
    i = 0
    while True:
        m = _ENV_RE.search(text, i)
        if not m:
            out.append(text[i:])
            break
        out.append(text[i:m.start()])
        name = m.group(1)
        content_end, after_end = _find_env_end(text, name, m.end())
        inner = text[m.end():content_end]
        if name in _DROP_ENVIRONMENTS:
            pass
        elif name in _LIST_ENVIRONMENTS:
            out.append(_format_list(name, _extract_environments(inner)))
        else:
            out.append(_extract_environments(inner))
        i = after_end
    return "".join(out)


def _process_macros(text):
    out = []
    i = 0
    n = len(text)
    while i < n:
        ch = text[i]
        if ch == "\\" and i + 1 < n:
            nxt = text[i + 1]
            if nxt in _ESCAPE_CHARS:
                out.append(nxt)
                i += 2
                continue
            if nxt in (",", " "):
                out.append(" ")
                i += 2
                continue
            if nxt == "\\":
                out.append("\n")
                i += 2
                continue
            if nxt.isalpha():
                m = _MACRO_RE.match(text, i)
                name = m.group(1)
                j    = m.end()
                if name in _SYMBOL_MACROS:
                    out.append(_SYMBOL_MACROS[name])
                    # An empty group only ends the macro's name.
                    if text.startswith("{}", j):
                        j += 2
                    i = j
                    continue
                if name == "reqterminal":
                    # \reqterminal[reason] -- drop, including the optional arg.
                    if j < n and text[j] == "[":
                        close = text.find("]", j)
                        if close != -1:
                            j = close + 1
                    i = j
                    continue
                if name in _DROP_ARG_MACROS:
                    # Skip an optional [..] argument first (e.g. the width in
                    # \localreqdiagram*[0.5\textwidth]{..}), or its brace
                    # arguments would not be found and would leak as text.
                    if j < n and text[j] == "[":
                        close = text.find("]", j)
                        if close != -1:
                            j = close + 1
                    _, j = _match_args(text, j, _DROP_ARG_MACROS[name])
                    i = j
                    continue
                if name == "pgsrc":
                    # \pgsrc{file}{line}{display} -> "display [file:line]"
                    args, j = _match_args(text, j, 3)
                    loc = ":".join(a.strip() for a in args[:2])
                    disp = _process_macros(args[2]).strip() if len(args) > 2 else ""
                    out.append(f"{disp} [{loc}]" if disp else f"[{loc}]")
                    i = j
                    continue
                if name == "footnote":
                    # \footnote{text} -> " [Note: text]", kept inline so the
                    # citation stays next to the claim it supports.
                    args, j = _match_args(text, j, 1)
                    if args:
                        out.append(f" [Note: {_process_macros(args[0]).strip()}]")
                    i = j
                    continue
                if name == "href":
                    # \href{url}{text} -> "text <url>"
                    args, j = _match_args(text, j, 2)
                    url = args[0].replace("\\#", "#") if args else ""
                    disp = _process_macros(args[1]).strip() if len(args) > 1 else ""
                    out.append(f"{disp} <{url}>" if disp else f"<{url}>")
                    i = j
                    continue
                if name in ("url", "path"):
                    args, j = _match_args(text, j, 1)
                    val = args[0].replace("\\#", "#") if args else ""
                    out.append(f"<{val}>" if name == "url" else f"`{val}`")
                    i = j
                    continue
                if name in _MD_WRAP_MACROS:
                    args, j = _match_args(text, j, 1)
                    left, right = _MD_WRAP_MACROS[name]
                    inner = _process_macros(args[0]) if args else ""
                    out.append(f"{left}{inner}{right}")
                    i = j
                    continue
                if name == "textsuperscript":
                    args, j = _match_args(text, j, 1)
                    out.append(_process_macros(args[0]) if args else "")
                    i = j
                    continue
                if name == "reqref":
                    # \reqref[display]{id} -> display text if given, else the id.
                    disp = None
                    if j < n and text[j] == "[":
                        close = text.find("]", j)
                        if close != -1:
                            disp = text[j + 1:close]
                            j = close + 1
                    args, j = _match_args(text, j, 1)
                    inner = disp if disp is not None else (args[0] if args else "")
                    out.append(_process_macros(inner))
                    i = j
                    continue
                if name == "rfcsec":
                    # \rfcsec{rfc}{section}[gloss] -> "RFC <rfc> Section <section> (gloss)"
                    args, j = _match_args(text, j, 2)
                    gloss = None
                    if j < n and text[j] == "[":
                        close = text.find("]", j)
                        if close != -1:
                            gloss = text[j + 1:close]
                            j = close + 1
                    rfc = args[0] if args else ""
                    sec = args[1] if len(args) > 1 else ""
                    ref = f"RFC {rfc} Section {sec}"
                    if gloss:
                        ref += f" ({_process_macros(gloss)})"
                    out.append(ref)
                    i = j
                    continue
                # Unknown macro: unwrap to its argument text (if any).
                unknown_macros_seen.add(name)
                args, j = _match_args(text, j, 1)
                if args:
                    out.append(_process_macros(args[0]))
                i = j
                continue
            out.append(nxt)
            i += 2
            continue
        if ch == "~":
            out.append(" ")
            i += 1
            continue
        out.append(ch)
        i += 1
    return "".join(out)


def strip_latex(raw):
    """Turn a detokenized reqbody-*.tex file's contents into plain prose."""
    text = raw.replace("\n", " ")
    text = re.sub(r"\\par\b\s*", "\n\n", text)
    text = _extract_environments(text)
    text = _process_macros(text)
    text = re.sub(r"[ \t]+", " ", text)
    text = re.sub(r" *\n *", "\n", text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()


# ── DOT layout parsing ─────────────────────────────────────────────────────────

def parse_dot_plain(dotpath):
    if not os.path.exists(dotpath):
        print(f"  WARNING: {dotpath} not found, skipping tikz generation")
        return None
    try:
        result = subprocess.run(
            ["dot", "-Tplain", dotpath],
            capture_output=True, text=True, check=True,
        )
    except Exception as e:
        print(f"  WARNING: dot -Tplain failed: {e}, skipping tikz generation")
        return None

    layout  = {"width": 0, "height": 0, "nodes": {}, "edges": []}
    # -Tplain quotes a node's name only when it needs to: an ID, with its
    # dots and hyphens, comes quoted; a bare word such as a domain does not.
    node_re = re.compile(
        r'^node\s+(?:"([^"]*)"|(\S+))\s+([0-9.]+)\s+([0-9.]+)\s+([0-9.]+)\s+([0-9.]+)')

    for line in result.stdout.strip().split("\n"):
        parts = line.split()
        if not parts:
            continue
        if parts[0] == "graph":
            layout["width"]  = float(parts[2])
            layout["height"] = float(parts[3])
        elif parts[0] == "node":
            m = node_re.match(line)
            if m:
                name = m.group(1) if m.group(1) is not None else m.group(2)
                layout["nodes"][name] = {
                    "cx": float(m.group(3)), "cy": float(m.group(4)),
                    "w":  float(m.group(5)), "h":  float(m.group(6)),
                }
        elif parts[0] == "edge":
            src   = parts[1].strip('"')
            tgt   = parts[2].strip('"')
            n_pts = int(parts[3])
            spline = [(float(parts[4 + 2*i]), float(parts[5 + 2*i])) for i in range(n_pts)]
            idx   = 4 + 2 * n_pts
            # The points are followed by "label xl yl style color", or by
            # "style color" alone when the edge has no label.
            has_label = len(parts) - idx >= 5
            label = parts[idx].strip('"') if has_label else ""
            lx    = float(parts[idx + 1]) if has_label else None
            ly    = float(parts[idx + 2]) if has_label else None
            layout["edges"].append({"src": src, "tgt": tgt, "spline": spline,
                                    "label": label, "lx": lx, "ly": ly})
    return layout


def spline_to_tikz(spline):
    if len(spline) < 4:
        return (f"({spline[0][0]:.4f}, {spline[0][1]:.4f})"
                f" -- ({spline[-1][0]:.4f}, {spline[-1][1]:.4f})")
    parts = [f"({spline[0][0]:.4f}, {spline[0][1]:.4f})"]
    for i in range(1, len(spline), 3):
        if i + 2 < len(spline):
            c1, c2, end = spline[i], spline[i + 1], spline[i + 2]
            parts.append(
                f".. controls ({c1[0]:.4f}, {c1[1]:.4f}) and ({c2[0]:.4f}, {c2[1]:.4f})"
                f" .. ({end[0]:.4f}, {end[1]:.4f})"
            )
    return " ".join(parts)


def tikz_node_name(aid):
    return f"n-{aid}"


