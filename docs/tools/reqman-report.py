def generate_layout_dot(outdir, jobname, artifacts, links, included_ids=None, label=None):
    """Write a fixedsize-rect DOT file for layout.

    included_ids=None → all artifacts (global diagram).
    included_ids=set  → only those nodes and the edges between them.
    label=None        → writes to {outdir}/{jobname}-req-layout.dot
    label="foo"       → writes to {outdir}/{jobname}-partial-foo-layout.dot
    """
    if included_ids is None:
        node_ids = [a["ID"] for a in artifacts]
        edge_links = links
    else:
        node_ids   = [a["ID"] for a in artifacts if a["ID"] in included_ids]
        edge_links = [l for l in links
                      if l["Source_ID"] in included_ids and l["Target_ID"] in included_ids]

    edges = []
    for lnk in edge_links:
        sysml_label = REL_MAP.get(lnk["Rel_Type"], (lnk["Rel_Type"],))[0]
        edges.append({"src": lnk["Source_ID"], "tgt": lnk["Target_ID"], "sysml_label": sysml_label})

    dotpath = (f"{outdir}/{jobname}-partial-{label}-layout.dot" if label
               else f"{outdir}/{jobname}-req-layout.dot")
    with open(dotpath, "w") as f:
        f.write(JINJA_ENV.from_string(TMPL_LAYOUT_DOT).render(
            node_width=NODE_DOT_WIDTH,
            node_height=NODE_DOT_HEIGHT,
            node_ids=node_ids,
            edges=edges,
        ))
    print(f"  wrote {dotpath}")
    return dotpath


def _build_tikz_context(artifacts, layout, neighbor_ids=None, hypertarget_prefix="diag:req"):
    """Build the template context dict for TMPL_TIKZ_DIAGRAM.

    layout should already contain only the nodes to render (pre-filtered).
    neighbor_ids: subset of those nodes to style in gray (border nodes in
    partial diagrams).  None or empty means all nodes are primary.
    """
    if neighbor_ids is None:
        neighbor_ids = set()

    art_by_id = {a["ID"]: a for a in artifacts}
    node_pos  = layout["nodes"]

    # Shift y so the bottom node starts near the origin.
    active = list(node_pos.values())
    if active:
        min_cy    = min(p["cy"] for p in active)
        cy_offset = min_cy - NODE_DOT_HEIGHT / 2
    else:
        cy_offset = 0.0

    # Colors — include neighbour grays so providecolor covers them
    all_hex = (
        set(STATUS_FILL.values())
        | set(SYSML_REQTYPE_COLORS.values())
        | {v[1] for v in REL_MAP.values()}
        | {"#CCCCCC", "#E0E0E0"}
    )
    colors = [{"name": f"c{h.lstrip('#')}", "hex": h.lstrip('#')} for h in sorted(all_hex)]

    edge_styles = [
        {"skey": sysml_label.strip("<>"), "cname": f"c{ecolor.lstrip('#')}"}
        for sysml_label, ecolor, *_ in REL_MAP.values()
    ]

    # Nodes — only those present in the (pre-filtered) layout
    nodes = []
    for a in artifacts:
        aid = a["ID"]
        if aid not in node_pos:
            continue
        pos         = node_pos[aid]
        is_neighbor = aid in neighbor_ids
        reqtype     = infer_reqtype(a)
        if is_neighbor:
            hdr_color  = NEIGHBOR_HDR_COLOR
            st_color   = NEIGHBOR_ST_COLOR
            stereotype = SYSML_REQTYPE_LABEL.get(reqtype, reqtype)
        else:
            hdr_color  = f"c{SYSML_REQTYPE_COLORS.get(reqtype, '#CCCCCC').lstrip('#')}"
            st_color   = f"c{STATUS_FILL.get(a['Status'], '#FFFFFF').lstrip('#')}"
            stereotype = SYSML_REQTYPE_LABEL.get(reqtype, reqtype)
        nodes.append({
            "nname":            f"({tikz_node_name(aid)})",
            "coord":            f"({pos['cx']:.4f}, {pos['cy'] - cy_offset:.4f})",
            "hdr_color":        hdr_color,
            "st_color":         st_color,
            "stereotype":       stereotype,
            "aid":              aid,
            "fmt_aid":          fmt_id(aid),
            "title":            fmt_title(a["Title"]),
            "status":           a["Status"],
            "col":              NODE_TIKZ_COL,
            "hypertarget_name": f"{hypertarget_prefix}:{aid}" if hypertarget_prefix else None,
        })

    # Edges — layout already only contains edges between included nodes
    edge_style_info = {v[0]: (v[1], v[2]) for v in REL_MAP.values()}
    edges = []
    for e in layout["edges"]:
        if e["src"] not in art_by_id or e["tgt"] not in art_by_id:
            continue
        label     = e["label"]
        skey      = label.strip("<>")
        info      = edge_style_info.get(label)
        has_label = e["lx"] is not None
        edges.append({
            "path":      spline_to_tikz([(x, y - cy_offset) for x, y in e["spline"]]),
            "skey":      skey,
            "dashed":    bool(info and info[1] == "dashed"),
            "has_label": has_label,
            "label":     label if has_label else "",
            "label_pos": f"({e['lx']:.4f}, {e['ly'] - cy_offset:.4f})" if has_label else "",
        })

    return {"colors": colors, "edge_styles": edge_styles,
            "nodes": nodes, "edges": edges, "label_pt": 7}


def generate_tikz_diagram(outdir, jobname, artifacts, layout, neighbor_ids=None, label=None,
                          label_pt=7):
    effective = label if label is not None else "global"
    prefix    = f"diag:{effective}"
    ctx       = _build_tikz_context(artifacts, layout, neighbor_ids,
                                    hypertarget_prefix=prefix)
    ctx["label_pt"] = label_pt
    filename = f"{outdir}/{jobname}-partial-{effective}-tikz.tikz"
    with open(filename, "w") as f:
        f.write(JINJA_ENV.from_string(TMPL_TIKZ_DIAGRAM).render(**ctx))
    print(f"  wrote {filename}")


def domain_of(aid):
    """The domain an ID names: the part of its sub-ID before the first dot
    (HLR-PERSISTENCE.DURABLE-01 belongs to PERSISTENCE)."""
    return aid.split("-")[1].split(".")[0]


def generate_overview_diagram(outdir, jobname, artifacts, links, type_order,
                              terminal_prefixes):
    r"""Write {outdir}/{jobname}-overview-tikz.tikz, the domain overview.

    One box per domain, with how many artifacts of each type it holds, types
    in type_order, the order the document declares them in; and one arrow per
    pair of domains that relationships other than trace link, from the domain
    they leave to the one they point to, labelled with how many there are of
    each kind, in the colours the other diagrams give the relationships. The
    domains are ranked by the stage of refinement their artifacts belong to
    (see TMPL_LAYOUT_OVERVIEW_DOT). Each artifact's
    \reqdiaglink{overview}{...} lands on its domain's box.
    """
    art_ids = {a["ID"] for a in artifacts}
    members = defaultdict(list)
    for a in artifacts:
        members[domain_of(a["ID"])].append(a["ID"])
    pair_counts = defaultdict(lambda: defaultdict(int))
    for lnk in links:
        src, tgt, rel = lnk["Source_ID"], lnk["Target_ID"], lnk["Rel_Type"]
        if rel == "trace" or src not in art_ids or tgt not in art_ids:
            continue
        if domain_of(src) != domain_of(tgt):
            pair_counts[(domain_of(src), domain_of(tgt))][rel] += 1

    domains = []
    for name in sorted(members):
        per_type = defaultdict(int)
        for aid in members[name]:
            per_type[aid.split("-")[0]] += 1
        types = ([t for t in type_order if per_type[t]]
                 + sorted(t for t in per_type if t not in type_order))
        plain = "  ".join(f"{t} {per_type[t]}" for t in types)
        width = max(OVERVIEW_NAME_CHAR_W * len(name), OVERVIEW_COUNT_CHAR_W * len(plain))
        domains.append({
            "name":   name,
            "width":  f"{width + OVERVIEW_BOX_PAD:.2f}",
            "ids":    sorted(members[name]),
            "counts": r"\enspace ".join(f"{t}~{per_type[t]}" for t in types),
        })
    # The document declares its types in the order of the refinement stages,
    # so a type's stage is its place among them. Terminal types close the
    # chain in every domain alike and do not count; a domain of terminal
    # artifacts alone comes after the last stage.
    stage_of_type = {t: i for i, t in
                     enumerate(t for t in type_order if t not in terminal_prefixes)}
    stage = {}
    for name, ids in members.items():
        stages = [stage_of_type[aid.split("-")[0]] for aid in ids
                  if aid.split("-")[0] in stage_of_type]
        stage[name] = sum(stages) / len(stages) if stages else len(stage_of_type)
    edges = [{"src": s, "tgt": t, "ranks": stage[s] >= stage[t],
              "dot_label": "_".join(f"{n}{REL_MAP[r][3]}" for r, n in rels.items())}
             for (s, t), rels in sorted(pair_counts.items())]

    dotpath = f"{outdir}/{jobname}-overview-layout.dot"
    with open(dotpath, "w") as f:
        f.write(JINJA_ENV.from_string(TMPL_LAYOUT_OVERVIEW_DOT).render(
            box_h=OVERVIEW_BOX_H, label_pt=OVERVIEW_LABEL_PT,
            domains=domains, edges=edges))
    print(f"  wrote {dotpath}")
    layout = parse_dot_plain(dotpath)
    if not (layout and layout["nodes"]):
        print("  WARNING: layout failed for the domain overview")
        return

    cname = lambda hexcolor: f"c{hexcolor.lstrip('#')}"
    for d in domains:
        pos = layout["nodes"][d["name"]]
        d["coord"] = f"({pos['cx']:.4f}, {pos['cy']:.4f})"
    tikz_edges = []
    for e in layout["edges"]:
        rels = pair_counts[(e["src"], e["tgt"])]
        tikz_edges.append({
            "path":      spline_to_tikz(e["spline"]),
            "width":     f"{min(2.5, 0.4 + 0.12 * sum(rels.values())):.2f}",
            "label":     "~".join(rf"\textcolor{{{cname(REL_MAP[r][1])}}}{{{rels[r]}{REL_MAP[r][3]}}}"
                                  for r in REL_MAP if rels.get(r)),
            "label_pos": f"({e['lx']:.4f}, {e['ly']:.4f})",
        })
    present = [r for r in REL_MAP if any(rels.get(r) for rels in pair_counts.values())]
    legend = r"\quad ".join(
        rf"\textcolor{{{cname(REL_MAP[r][1])}}}{{{REL_MAP[r][3]}~{REL_MAP[r][0].strip('<>')}}}"
        for r in present)
    colors = {OVERVIEW_DOMAIN_FILL, OVERVIEW_LINK_COLOR} | {REL_MAP[r][1] for r in present}

    filename = f"{outdir}/{jobname}-overview-tikz.tikz"
    with open(filename, "w") as f:
        f.write(JINJA_ENV.from_string(TMPL_TIKZ_OVERVIEW).render(
            colors=[{"name": cname(h), "hex": h.lstrip("#")} for h in sorted(colors)],
            domain_fill=cname(OVERVIEW_DOMAIN_FILL), link_color=cname(OVERVIEW_LINK_COLOR),
            box_h=OVERVIEW_BOX_H, name_pt=OVERVIEW_NAME_PT, counts_pt=OVERVIEW_COUNTS_PT,
            label_pt=OVERVIEW_LABEL_PT, domains=domains, edges=tikz_edges, legend=legend,
            bbox=(f"(0, -{OVERVIEW_LEGEND_H}) rectangle "
                  f"({layout['width']:.4f}, {layout['height']:.4f})"),
            legend_at=f"({layout['width'] / 2:.4f}, -0.06)"))
    print(f"  wrote {filename}")


def star_layout_parts(focus_ids, links, art_by_id):
    """Lay out a focus artifact's neighbourhood as a star, without DOT.

    Neighbours the focus points to (the targets of its own relationships) sit
    in a row above it; neighbours pointing to it sit in a row below. A row
    holds at most STAR_PER_ROW cards, so a larger neighbourhood is split into
    parts, each repeating the focus. Only edges between the focus and a
    neighbour are drawn, straight, so none crosses a card. Returns a list of
    (layout, neighbor_ids) pairs in the shape parse_dot_plain produces.
    """
    rel_order = {rel: i for i, rel in enumerate(REL_MAP)}
    above, below, pair_links = {}, {}, {}
    for lnk in links:
        src, tgt, rel = lnk["Source_ID"], lnk["Target_ID"], lnk["Rel_Type"]
        if src in focus_ids and tgt not in focus_ids and tgt in art_by_id:
            above.setdefault(tgt, rel_order.get(rel, len(rel_order)))
            pair_links.setdefault(tgt, []).append(lnk)
        elif tgt in focus_ids and src not in focus_ids and src in art_by_id:
            below.setdefault(src, rel_order.get(rel, len(rel_order)))
            pair_links.setdefault(src, []).append(lnk)
    for aid in above:
        below.pop(aid, None)
    order = lambda group: sorted(group, key=lambda aid: (group[aid], aid))
    up, down = order(above), order(below)
    focus = [aid for aid in art_by_id if aid in focus_ids]
    if not focus:
        return []

    per = STAR_PER_ROW
    nparts = max(1, -(-len(up) // per), -(-len(down) // per))
    pitch = STAR_CARD_W + STAR_GAP_X
    half_h = STAR_CARD_H / 2

    def row_xs(n):
        return [(i - (n - 1) / 2) * pitch for i in range(n)]

    parts = []
    for p in range(nparts):
        up_p, down_p = up[p * per:(p + 1) * per], down[p * per:(p + 1) * per]
        rows = ([down_p] if down_p else []) + [focus] + ([up_p] if up_p else [])
        nodes = {}
        for r, row in enumerate(rows):
            for aid, x in zip(row, row_xs(len(row))):
                nodes[aid] = {"cx": x, "cy": r * (STAR_CARD_H + STAR_GAP_Y),
                              "w": STAR_CARD_W, "h": STAR_CARD_H}
        f = nodes[focus[0]]

        # Spread the edges' ends along each side of the focus card, in the
        # left-to-right order of the neighbours they reach.
        edges = []
        for side, row in (("top", up_p), ("bottom", down_p)):
            side_links = [l for aid in row for l in pair_links[aid]]
            m = len(side_links)
            step = min(0.45, (STAR_CARD_W - 0.4) / max(1, m - 1)) if m > 1 else 0
            per_pair = {}
            for k, lnk in enumerate(side_links):
                other = lnk["Target_ID"] if lnk["Source_ID"] in focus_ids else lnk["Source_ID"]
                n = nodes[other]
                j = per_pair.get(other, 0)
                per_pair[other] = j + 1
                count = len(pair_links[other])
                dx_other = (j - (count - 1) / 2) * 0.5
                fx = f["cx"] + (k - (m - 1) / 2) * step
                if side == "top":
                    fpt = (fx, f["cy"] + half_h)
                    npt = (n["cx"] + dx_other, n["cy"] - half_h)
                else:
                    fpt = (fx, f["cy"] - half_h)
                    npt = (n["cx"] + dx_other, n["cy"] + half_h)
                start, end = (fpt, npt) if lnk["Source_ID"] in focus_ids else (npt, fpt)
                t = 0.5 if count == 1 else 0.35 + 0.3 * j / (count - 1)
                sysml_label = REL_MAP.get(lnk["Rel_Type"], (lnk["Rel_Type"],))[0]
                edges.append({
                    "src": lnk["Source_ID"], "tgt": lnk["Target_ID"],
                    "spline": [start, end], "label": sysml_label,
                    "lx": fpt[0] + (npt[0] - fpt[0]) * t,
                    "ly": fpt[1] + (npt[1] - fpt[1]) * t,
                })
        parts.append(({"width": 0, "height": 0, "nodes": nodes, "edges": edges},
                      set(up_p) | set(down_p)))
    return parts


def _group_rels(out_pairs, in_pairs):
    """Group outgoing and incoming rel pairs into labelled rows for the table."""
    from collections import OrderedDict
    groups = OrderedDict()
    for tgt, rtype in sorted(out_pairs):
        lbl = OUTGOING_REL_LABELS.get(rtype, rtype)
        groups.setdefault(lbl, []).append(
            rf"\hyperref[req:{tgt}]{{{fmt_id(tgt)}}}"
        )
    for src, rtype in sorted(in_pairs):
        lbl = MAPPING_RELATIONSHIPS.get(rtype, rtype)
        groups.setdefault(lbl, []).append(
            rf"\hyperref[req:{src}]{{{fmt_id(src)}}}"
        )
    return [{"label": lbl, "targets": items} for lbl, items in groups.items()]


def covered_pairs_by_target(links):
    """For each target requirement, the set of (source-prefix, relationship)
    pairs of its incoming links. A \\reqcover{rel}{PREFIX} obligation on the
    target is met when (PREFIX, rel) is in this set."""
    covered = defaultdict(set)
    for lnk in links:
        prefix = lnk["Source_ID"].split("-")[0]
        covered[lnk["Target_ID"]].add((prefix, lnk["Rel_Type"]))
    return covered


def covered_specific_by_target(links):
    """For each target requirement, the set of (source-ID, relationship)
    pairs of its incoming links. A \\reqexpect{rel}{FULL-ID}{note} obligation
    on the target is met only when (FULL-ID, rel) is in this set -- exact-ID
    match, no prefix fallback."""
    covered = defaultdict(set)
    for lnk in links:
        covered[lnk["Target_ID"]].add((lnk["Source_ID"], lnk["Rel_Type"]))
    return covered


def obligations_by_req(obligations):
    """Group parsed \\reqcover/\\reqexpect rows into
    {Source_ID: [{"rel", "prefix", "target_id", "note"}, ...]}."""
    cover_by_req = defaultdict(list)
    for row in obligations:
        cover_by_req[row["Source_ID"]].append({
            "rel":       row["Rel"],
            "prefix":    row["Prefix"],
            "target_id": row["Required_ID"],
            "note":      row["Note"],
        })
    return cover_by_req


def obligation_met(ob, aid, covered_pairs, covered_specific):
    """Whether one coverage obligation on requirement `aid` is satisfied.
    A \\reqexpect obligation (target_id set) requires an exact-ID match; a
    \\reqcover obligation (prefix only) is met by any matching prefix."""
    if ob["target_id"]:
        return (ob["target_id"], ob["rel"]) in covered_specific.get(aid, set())
    return (ob["prefix"], ob["rel"]) in covered_pairs.get(aid, set())


def fmt_obligation(ob, prefix_reqtype, all_ids):
    """Render one coverage obligation as LaTeX: 'RFR via <<refine>>' for a
    class-level \\reqcover, or the hyperlinked/planned ID plus its note for a
    specific \\reqexpect. Unknown prefixes/relations are shown in red."""
    rel     = ob["rel"]
    known_r = rel in REL_MAP
    rel_lbl = rf"\textit{{$\langle\langle${rel}$\rangle\rangle$}}"
    disp_r  = rel_lbl if known_r else rf"\textcolor{{red}}{{{rel_lbl}}}"

    if ob["target_id"]:
        tid = ob["target_id"]
        if tid in all_ids:
            disp_t = rf"\hyperref[req:{tid}]{{\reqbreakid{{{tid}}}}}"
        else:
            disp_t = rf"\textit{{\reqbreakid{{{tid}}}}} (not yet written)"
        out = rf"{disp_t} via {disp_r}"
        if ob["note"]:
            out += rf" --- \textit{{{fmt_title(ob['note'])}}}"
        return out

    pfx     = ob["prefix"]
    known_p = prefix_reqtype is None or pfx in prefix_reqtype
    disp_p  = fmt_id(pfx) if known_p else rf"\textcolor{{red}}{{{fmt_id(pfx)}}}"
    return rf"{disp_p} via {disp_r}"


def generate_tracing_report(outdir, jobname, artifacts, links, obligations, prefix_reqtype,
                             type_descriptions, undeclared_types, terminal_prefixes,
                             terminal_reqs, ext_links=()):
    counts = defaultdict(lambda: defaultdict(int))
    for a in artifacts:
        counts[a["Type"]][a["Status"]] += 1
    types    = sorted(counts.keys())
    statuses = sorted({s for v in counts.values() for s in v})

    table_rows = []
    for t in types:
        count_values = [counts[t].get(s, 0) for s in statuses]
        table_rows.append({
            "type_fmt":     fmt_id(t),
            "undeclared":   t in undeclared_types,
            "count_values": count_values,
            "total":        sum(count_values),
        })

    totals_row = {
        "count_values": [sum(row["count_values"][i] for row in table_rows)
                          for i in range(len(statuses))],
        "total":        sum(row["total"] for row in table_rows),
    }

    # Not Yet Accepted: every artifact whose status isn't "accepted" (case-
    # insensitively), grouped by its actual status string and sorted
    # alphabetically both across groups and within each one.
    not_accepted_by_status = defaultdict(list)
    for a in artifacts:
        if a["Status"].strip().lower() != "accepted":
            not_accepted_by_status[a["Status"]].append(a)

    not_accepted_groups = []
    for status in sorted(not_accepted_by_status.keys()):
        items = sorted(not_accepted_by_status[status], key=lambda a: (a["Type"], a["ID"]))
        not_accepted_groups.append({
            "status": status,
            "count":  len(items),
            "plural": "" if len(items) == 1 else "s",
            "reqs": [
                {
                    "aid":       a["ID"],
                    "aid_fmt":   fmt_id(a["ID"]),
                    "type_fmt":  fmt_id(a["Type"]),
                    "title_fmt": fmt_title(a["Title"]),
                }
                for a in items
            ],
        })

    outgoing = defaultdict(list)
    incoming = defaultdict(list)
    for lnk in links:
        outgoing[lnk["Source_ID"]].append((lnk["Target_ID"], lnk["Rel_Type"]))
        incoming[lnk["Target_ID"]].append((lnk["Source_ID"], lnk["Rel_Type"]))

    cover_by_req     = obligations_by_req(obligations)
    covered_pairs    = covered_pairs_by_target(links + list(ext_links))
    covered_specific = covered_specific_by_target(links + list(ext_links))

    all_ids    = {a["ID"] for a in artifacts}
    linked_ids = {lnk["Source_ID"] for lnk in links} | {lnk["Target_ID"] for lnk in links}
    orphan_ids = all_ids - linked_ids - set(cover_by_req)

    entries = []
    for a in artifacts:
        aid        = a["ID"]
        out_pairs  = outgoing.get(aid, [])
        in_pairs   = incoming.get(aid, [])
        cover      = cover_by_req.get(aid, [])
        if not out_pairs and not in_pairs and not cover:
            continue
        reqtype  = infer_reqtype(a)
        rel_rows = _group_rels(out_pairs, in_pairs)
        if cover:
            items = []
            for ob in cover:
                met    = obligation_met(ob, aid, covered_pairs, covered_specific)
                symbol = r"$\checkmark$" if met else r"$\square$"
                items.append(rf"{symbol}~{fmt_obligation(ob, prefix_reqtype, all_ids)}")
            rel_rows.append({"label": "Required coverage", "targets": items})
        entries.append({
            "aid":           aid,
            "aid_fmt":       fmt_id(aid),
            "type_fmt":      fmt_id(a["Type"]),
            "title_fmt":     fmt_title(a["Title"]),
            "status":        a["Status"],
            "reqtype_label": SYSML_REQTYPE_LABEL.get(reqtype, reqtype),
            "undeclared":    a["Type"] in undeclared_types,
            "rel_rows":      rel_rows,
        })

    orphans = [
        {
            "aid":       a["ID"],
            "aid_fmt":   fmt_id(a["ID"]),
            "type_fmt":  fmt_id(a["Type"]),
            "title_fmt": fmt_title(a["Title"]),
        }
        for a in artifacts if a["ID"] in orphan_ids
    ]

    coverage_gaps = []
    for a in artifacts:
        aid     = a["ID"]
        cover   = cover_by_req.get(aid, [])
        missing = [fmt_obligation(ob, prefix_reqtype, all_ids)
                   for ob in cover if not obligation_met(ob, aid, covered_pairs, covered_specific)]
        if missing:
            coverage_gaps.append({
                "aid":       aid,
                "aid_fmt":   fmt_id(aid),
                "type_fmt":  fmt_id(a["Type"]),
                "title_fmt": fmt_title(a["Title"]),
                "missing":   missing,
            })

    # Planned Requirements: unmet \reqexpect obligations, grouped by the
    # specific target ID they forward-declare (which may not exist yet).
    planned = defaultdict(list)
    for aid, obs in cover_by_req.items():
        for ob in obs:
            if ob["target_id"] and not obligation_met(ob, aid, covered_pairs, covered_specific):
                planned[ob["target_id"]].append({
                    "source_aid": aid,
                    "rel":        ob["rel"],
                    "rel_known":  ob["rel"] in REL_MAP,
                    "note_fmt":   fmt_title(ob["note"]) if ob["note"] else "",
                })

    planned_groups = []
    for tid in sorted(planned.keys()):
        expectations = sorted(planned[tid], key=lambda e: e["source_aid"])
        planned_groups.append({
            "target_id":    tid,
            "exists":       tid in all_ids,
            "expectations": expectations,
        })

    # Completeness check: every artifact should either state what downstream
    # coverage it expects or be terminal (by type flag, \reqterminal, or
    # deprecation).
    unaccounted = [
        {
            "aid":       a["ID"],
            "aid_fmt":   fmt_id(a["ID"]),
            "type_fmt":  fmt_id(a["Type"]),
            "title_fmt": fmt_title(a["Title"]),
        }
        for a in artifacts
        if a["ID"] not in cover_by_req
        and a["ID"] not in terminal_reqs
        and a["Type"] not in terminal_prefixes
        and a["Status"].strip().lower() != "deprecated"
    ]

    # Build stereotype rows: types that appear in the document, in the order the
    # document declares them (its flow of refinement), undeclared types last
    decl_order = {t: i for i, t in enumerate(type_descriptions)}
    seen_types = sorted(counts.keys(), key=lambda t: (decl_order.get(t, len(decl_order)), t))
    stereotype_rows = []
    for t in seen_types:
        reqtype = prefix_reqtype.get(t, "requirement")
        desc    = type_descriptions.get(t, SYSML_REQTYPE_LABEL.get(reqtype, reqtype))
        stereotype_rows.append({
            "prefix":      fmt_id(t),
            "reqtype":     SYSML_REQTYPE_LABEL.get(reqtype, reqtype),
            "description": desc if t not in undeclared_types else "Undeclared type",
            "undeclared":  t in undeclared_types,
        })

    path = f"{outdir}/{jobname}-tracing-report.tex"
    with open(path, "w") as f:
        f.write(JINJA_ENV.from_string(TMPL_TRACING_REPORT).render(
            statuses=statuses,
            table_rows=table_rows,
            totals_row=totals_row,
            entries=entries,
            orphans=orphans,
            has_orphans=bool(orphans),
            coverage_gaps=coverage_gaps,
            has_coverage_gaps=bool(coverage_gaps),
            planned_groups=planned_groups,
            has_planned=bool(planned_groups),
            unaccounted=unaccounted,
            has_unaccounted=bool(unaccounted),
            has_undeclared=bool(undeclared_types),
            not_accepted_groups=not_accepted_groups,
            has_not_accepted=bool(not_accepted_groups),
        ))
    print(f"  wrote {path}")

    # Standalone stereotype reference fragment (see \includereqstereotypes in
    # reqman.sty) -- same data, placeable anywhere.
    stereotypes_path = f"{outdir}/{jobname}-stereotypes.tex"
    with open(stereotypes_path, "w") as f:
        f.write(JINJA_ENV.from_string(TMPL_REQ_STEREOTYPES).render(stereotype_rows=stereotype_rows))
    print(f"  wrote {stereotypes_path}")


def build_source_index(source_root, skip_dirs=()):
    """Scan .tex files under source_root for ``\\begin{requirement}{ID}`` and map
    each ID to where it is defined: {"file": <relative path>, "line": <1-based>}.
    This lets requirements.json carry a source pointer so an editor or an agent
    can jump straight to a requirement's definition without parsing LaTeX.
    Commented-out definitions (line starts with '%') are skipped; the first
    definition of an ID wins."""
    skip   = {os.path.normpath(os.path.join(source_root, d)) for d in skip_dirs}
    pat    = re.compile(r"\\begin\{requirement\}\{([^}]+)\}")
    index  = {}
    for dirpath, dirnames, filenames in os.walk(source_root):
        dirnames[:] = [d for d in dirnames
                       if os.path.normpath(os.path.join(dirpath, d)) not in skip]
        for fn in sorted(filenames):
            if not fn.endswith(".tex"):
                continue
            path = os.path.join(dirpath, fn)
            try:
                with open(path, encoding="utf-8") as f:
                    for lineno, line in enumerate(f, start=1):
                        if line.lstrip().startswith("%"):
                            continue
                        m = pat.search(line)
                        if m:
                            index.setdefault(m.group(1).strip(), {
                                "file": os.path.relpath(path, source_root),
                                "line": lineno,
                            })
            except (OSError, UnicodeDecodeError):
                continue
    return index


# ── IMP-comment extraction (source code → requirements traceability) ──────────
#
# Design/functional artifacts (FDS, SDS, ...) declare a class-level coverage
# obligation `\reqcover{satisfy}{IMP}` for the requirements only the actual
# implementation can close -- there is no LaTeX artifact for "the code",
# so that obligation can never be satisfied from links.csv alone. Instead,
# implementation source files carry their own marker comments:
#
#   // IMP-<SLUG>-<NN>: <relationship> <TARGET-ID> [optional note]
#   // IMP-STORAGE.PUBLISH-01: satisfy FDS-STORAGE.PUBLISH-01
#
# The IMP id is a real, citable identifier (same PREFIX-SLUG-NN shape as
# every other requirement ID in this project), authored deliberately at the
# implementation site, not derived from file/line -- file/line is only used
# for the display text and source link. extract_imp_links() turns every such
# comment into a row shaped exactly like an externals.csv row (Source_ID =
# the IMP id, Target_ID = what it satisfies), so callers can simply
# concatenate the two lists.

SOURCE_EXTENSIONS = {".rs"}
SOURCE_SKIP_DIRS  = {"target", "third_party", "node_modules", ".git", "docs"}


def source_url(path, relpath, lineno):
    """The URL an IMP link points at. REQMAN_SOURCE_URL is a template with
    {path} (the marker's file relative to the repository root, '/'-separated)
    and {line}; docs/latexmkrc points it at the published source. Unset, or
    set to "file", the link is the file:// URL of the marker's file in the
    building checkout -- handy for reading locally, but it records that
    checkout's absolute path in the PDF."""
    template = os.environ.get("REQMAN_SOURCE_URL", "").strip()
    if template in ("", "file"):
        return f"file://{os.path.abspath(path)}"
    return template.format(path=relpath.replace(os.sep, "/"), line=lineno)

# Reused for both the IMP id itself and its target: PREFIX-SLUG[.SUB...]-NN,
# e.g. "FDS-STORAGE.PUBLISH-01", "IMP-STORAGE.PUBLISH-01", "HLR-SCOPE.V1-01".
_REQ_ID_PATTERN = r"[A-Z]+-[A-Za-z0-9.]+-\d+"

_IMP_MARKER_RE = re.compile(
    r"(IMP-[A-Za-z0-9.]+-\d+):\s*"
    r"(" + "|".join(sorted(MAPPING_RELATIONSHIPS.keys(), key=len, reverse=True)) + r")\s+"
    r"(" + _REQ_ID_PATTERN + r")"
    r"(?:\s+(.+))?$"
)


def extract_imp_links(repo_root, skip_dirs=SOURCE_SKIP_DIRS):
    """Scan source files under repo_root for IMP marker comments (see above)
    and return rows shaped like externals.csv: Source_ID/Target_ID/Rel_Type/
    URL/Display. A marker must be the entire content of a comment line (after
    leading whitespace and the `//`/`///`/`//!` leader) -- this keeps markers
    greppable as dedicated lines and avoids false positives from a stray
    ID-shaped token in a trailing end-of-line comment.

    Duplicate IMP ids (the same id authored twice) are warned about, not
    fatal -- like every other soft-validation warning in this script."""
    skip  = set(skip_dirs)
    links = []
    first_seen = {}
    for dirpath, dirnames, filenames in os.walk(repo_root):
        dirnames[:] = [d for d in dirnames if d not in skip and not d.startswith(".")]
        for fn in sorted(filenames):
            if os.path.splitext(fn)[1] not in SOURCE_EXTENSIONS:
                continue
            path    = os.path.join(dirpath, fn)
            relpath = os.path.relpath(path, repo_root)
            try:
                with open(path, encoding="utf-8") as f:
                    lines = f.readlines()
            except (OSError, UnicodeDecodeError):
                continue
            for lineno, line in enumerate(lines, start=1):
                stripped = line.strip()
                if not stripped.startswith("//"):
                    continue
                m = _IMP_MARKER_RE.search(stripped)
                if not m:
                    continue
                imp_id, rel, target, note = m.groups()
                loc = f"{relpath}:{lineno}"
                if imp_id in first_seen:
                    print(f"  WARNING: duplicate IMP id {imp_id} at {loc} "
                          f"(first seen at {first_seen[imp_id]})")
                else:
                    first_seen[imp_id] = loc
                display = f"{imp_id} ({loc})"
                if note:
                    display += f" -- {note.strip()}"
                links.append({
                    "Source_ID": imp_id,
                    "Target_ID": target,
                    "Rel_Type":  rel,
                    "URL":       source_url(path, relpath, lineno),
                    "Display":   display,
                })
    return links


def generate_requirements_json(outdir, jobname, artifacts, links, obligations,
                                prefix_reqtype, undeclared_types, terminal_prefixes,
                                terminal_reqs, source_index=None, ext_links=()):
    """Consolidated <jobname>-requirements.json: metadata + plain-prose body
    + resolved relationships + coverage status for every requirement, for
    reqman-context.py (and coding agents) to query without parsing LaTeX.

    The .json is kept alongside the PDF (the repo root, i.e. no outdir prefix)
    while reqbody-*.tex fragments are read from outdir (the configured
    generated-files directory, e.g. build/).

    ext_links (externals.csv rows plus source-derived IMP links) feeds only
    coverage-obligation checking here, not the internal relationships dict:
    an external/IMP source has no artifact entry of its own to hyperlink to
    in this JSON, but a `\\reqcover{satisfy}{IMP}` obligation should still
    read as met once source code actually satisfies it."""
    outgoing = defaultdict(list)
    incoming = defaultdict(list)
    for lnk in links:
        outgoing[lnk["Source_ID"]].append((lnk["Target_ID"], lnk["Rel_Type"]))
        incoming[lnk["Target_ID"]].append((lnk["Source_ID"], lnk["Rel_Type"]))

    cover_by_req     = obligations_by_req(obligations)
    covered_pairs    = covered_pairs_by_target(links + list(ext_links))
    covered_specific = covered_specific_by_target(links + list(ext_links))

    # Invert \reqexpect obligations: for each forward-declared target ID,
    # who expects coverage from it, via what relation, and with what note --
    # regardless of whether that target exists yet.
    expected_by = defaultdict(list)
    for src_aid, obs in cover_by_req.items():
        for ob in obs:
            if ob["target_id"]:
                expected_by[ob["target_id"]].append({
                    "source": src_aid,
                    "rel":    ob["rel"],
                    "note":   ob["note"],
                    "met":    obligation_met(ob, src_aid, covered_pairs, covered_specific),
                })

    requirements = {}
    for a in artifacts:
        aid     = a["ID"]
        reqtype = infer_reqtype(a)

        body_path = f"{outdir}/{jobname}-reqbody-{aid}.tex"
        body = ""
        if os.path.exists(body_path):
            with open(body_path) as f:
                body = strip_latex(f.read())

        relationships = defaultdict(list)
        for tgt, rtype in outgoing.get(aid, []):
            relationships[OUTGOING_REL_KEYS.get(rtype, rtype)].append(tgt)
        for src, rtype in incoming.get(aid, []):
            relationships[INCOMING_REL_KEYS.get(rtype, rtype)].append(src)

        cover     = cover_by_req.get(aid, [])
        cov_block = {
            "required": [
                {
                    "rel":       ob["rel"],
                    "prefix":    ob["prefix"],
                    "target_id": ob["target_id"] or None,
                    "note":      ob["note"],
                    "met":       obligation_met(ob, aid, covered_pairs, covered_specific),
                }
                for ob in cover
            ],
            "terminal": aid in terminal_reqs or a["Type"] in terminal_prefixes,
        }
        if terminal_reqs.get(aid):
            cov_block["terminal_reason"] = terminal_reqs[aid]

        requirements[aid] = {
            "type":          a["Type"],
            "reqtype":       reqtype,
            "reqtype_label": SYSML_REQTYPE_LABEL.get(reqtype, reqtype),
            "title":         a["Title"],
            "status":        a["Status"],
            "undeclared":    a["Type"] in undeclared_types,
            "source":        (source_index or {}).get(aid),
            "body":          body,
            "relationships": dict(relationships),
            "coverage":      cov_block,
            "expected_by":   expected_by.get(aid, []),
        }

    path = f"{jobname}-requirements.json"
    with open(path, "w") as f:
        json.dump(requirements, f, indent=2, ensure_ascii=False)
    print(f"  wrote {path}")

    # Forward-declared obligations whose target ID has no artifact yet --
    # queryable before the requirement is ever drafted (e.g. by
    # reqman-context or the req-writing skill).
    art_ids      = {a["ID"] for a in artifacts}
    pending      = {tid: exps for tid, exps in expected_by.items() if tid not in art_ids}
    pending_path = f"{jobname}-pending-coverage.json"
    if pending:
        with open(pending_path, "w") as f:
            json.dump(pending, f, indent=2, ensure_ascii=False)
        print(f"  wrote {pending_path} ({len(pending)} pending ID(s))")
    elif os.path.exists(pending_path):
        os.remove(pending_path)


def generate_types_json(jobname, prefix_reqtype, type_descriptions, terminal_prefixes):
    r"""<jobname>-types.json, beside <jobname>-requirements.json: the artifact
    types as the document declares them with \reqmantype, in declaration
    order, for tools such as reqman-context that need the types without the
    LaTeX build. Each entry gives the prefix, the stereotype and its
    label, the description, and whether the type is terminal."""
    types = [{
        "prefix":      prefix,
        "reqtype":     reqtype,
        "label":       SYSML_REQTYPE_LABEL.get(reqtype, reqtype),
        "description": type_descriptions.get(prefix, ""),
        "terminal":    prefix in terminal_prefixes,
    } for prefix, reqtype in prefix_reqtype.items()]
    path = f"{jobname}-types.json"
    with open(path, "w") as f:
        json.dump(types, f, indent=2, ensure_ascii=False)
    print(f"  wrote {path}")


def generate_reqtables(outdir, jobname, artifacts, links, obligations, ext_links,
                       prefix_reqtype=None, terminal_reqs=None):
    cover_by_req     = obligations_by_req(obligations)
    covered_pairs    = covered_pairs_by_target(links + list(ext_links))
    covered_specific = covered_specific_by_target(links + list(ext_links))
    terminal_reqs    = terminal_reqs or {}

    out_rels = defaultdict(list)
    in_rels  = defaultdict(list)
    for lnk in links:
        rel_type = lnk["Rel_Type"]
        if rel_type in OUTGOING_REL_LABELS:
            out_rels[lnk["Source_ID"]].append({"label": OUTGOING_REL_LABELS[rel_type], "target": lnk["Target_ID"]})
        if rel_type in MAPPING_RELATIONSHIPS:
            in_rels[lnk["Target_ID"]].append({"label": MAPPING_RELATIONSHIPS[rel_type], "target": lnk["Source_ID"]})

    # Index external links: outgoing (internal→external) and incoming (external→internal)
    art_ids  = {a["ID"] for a in artifacts}
    ext_out  = defaultdict(list)   # internal aid → [{rel_type, url, display}]
    ext_in   = defaultdict(list)   # internal aid → [{rel_type, url, display}]
    for row in ext_links:
        src      = row.get("Source_ID", "").strip()
        tgt      = row.get("Target_ID", "").strip()
        rel_type = row.get("Rel_Type",  "").strip()
        url      = row.get("URL",       "").strip()
        display  = row.get("Display",   "").strip() or tgt or src
        if not url:
            continue
        if src in art_ids and tgt not in art_ids:
            ext_out[src].append({"rel_type": rel_type, "url": url, "display": display})
        elif tgt in art_ids and src not in art_ids:
            ext_in[tgt].append({"rel_type": rel_type, "url": url, "display": display})

    def _make_rows(aid):
        rows = []
        cover = cover_by_req.get(aid, [])
        if cover:
            items = []
            for ob in cover:
                met    = obligation_met(ob, aid, covered_pairs, covered_specific)
                symbol = r"$\checkmark$" if met else r"$\square$"
                items.append(rf"{symbol}~{fmt_obligation(ob, prefix_reqtype, art_ids)}")
            rows.append({"label": "Required coverage", "cell": r"\newline ".join(items)})
        elif aid in terminal_reqs:
            reason = terminal_reqs[aid]
            cell   = r"\textit{terminal}" + (f" --- {fmt_title(reason)}" if reason else "")
            rows.append({"label": "Required coverage", "cell": cell})

        # Collect rendered LaTeX strings per label, merging internal + external
        groups = {}
        order  = []

        def _add(lbl, rendered):
            if lbl not in groups:
                groups[lbl] = []
                order.append(lbl)
            if rendered not in groups[lbl]:
                groups[lbl].append(rendered)

        # \href arguments end up inside tabularx cells (read as macro
        # arguments), where a raw '#' or '%' breaks TeX; escape them.
        def _tex_url(u):
            return u.replace("#", r"\#").replace("%", r"\%")

        def _tex_text(t):
            for ch in "&%#_":
                t = t.replace(ch, "\\" + ch)
            return t

        for entry in out_rels.get(aid, []) + in_rels.get(aid, []):
            _add(entry["label"],
                 rf"\hyperref[req:{entry['target']}]{{{fmt_id(entry['target'])}}}")
        for ext in ext_out.get(aid, []):
            lbl = OUTGOING_REL_LABELS.get(ext["rel_type"], ext["rel_type"])
            _add(lbl, rf"\href{{{_tex_url(ext['url'])}}}{{{_tex_text(ext['display'])}}}")
        for ext in ext_in.get(aid, []):
            lbl = MAPPING_RELATIONSHIPS.get(ext["rel_type"], ext["rel_type"])
            _add(lbl, rf"\href{{{_tex_url(ext['url'])}}}{{{_tex_text(ext['display'])}}}")

        for lbl in order:
            cell = r"\newline ".join(groups[lbl])
            rows.append({"label": lbl, "cell": cell})
        return rows

    template = JINJA_ENV.from_string(TMPL_REQTABLES)
    written  = 0
    for a in artifacts:
        aid  = a["ID"]
        rows = _make_rows(aid)
        if rows:
            with open(f"{outdir}/{jobname}-reqtables-{aid}.tex", "w") as f:
                f.write(template.render(rows=rows))
            written += 1
    print(f"  wrote {written} reqtables files")


def generate_coverage_report(outdir, jobname, artifacts, links):
    incoming_by_rel = defaultdict(lambda: defaultdict(set))
    for lnk in links:
        if lnk["Rel_Type"] in RELATIONSHIPS:
            incoming_by_rel[lnk["Target_ID"]][lnk["Rel_Type"]].add(lnk["Source_ID"])

    template = JINJA_ENV.from_string(TMPL_COVERAGE)
    written  = 0
    for a in artifacts:
        aid        = a["ID"]
        rel_groups = incoming_by_rel.get(aid, {})
        groups     = [
            {"label": MAPPING_RELATIONSHIPS[rel_type], "srcs": sorted(rel_groups[rel_type])}
            for rel_type in sorted(rel_groups.keys())
        ]
        with open(f"{outdir}/{jobname}-coverage-{aid}.tex", "w") as f:
            f.write(template.render(groups=groups))
        written += 1
    print(f"  wrote {written} coverage files")


# ── Entry point ────────────────────────────────────────────────────────────────

def main():
    if len(sys.argv) < 2:
        print("Usage: reqman-report.py <jobname> [outdir]")
        sys.exit(1)
    jobname = sys.argv[1]
    outdir  = sys.argv[2] if len(sys.argv) > 2 else "."
    outdir  = "." if outdir == "" else outdir
    os.makedirs(outdir, exist_ok=True)
    print(f"reqman-report: processing {jobname}"
          + (f" (generated files in {outdir}/)" if outdir != "." else ""))

    artifacts     = load_csv(f"{outdir}/{jobname}-artifacts.csv")
    links         = load_csv(f"{outdir}/{jobname}-links.csv")
    coverage      = load_csv(f"{outdir}/{jobname}-coverage.csv")
    externals_csv = load_csv(f"{jobname}-externals.csv")
    imp_links     = extract_imp_links(REPO_ROOT)
    ext_links     = externals_csv + imp_links
    type_rows     = load_csv(f"{outdir}/{jobname}-types.csv")
    vocab         = load_csv(f"{outdir}/{jobname}-reqtypes-vocab.csv")
    print(f"  artifacts: {len(artifacts)}, links: {len(links)}, "
          f"coverage records: {len(coverage)}, external links: {len(externals_csv)}, "
          f"source-derived IMP links: {len(imp_links)}, declared types: {len(type_rows)}")

    art_ids_all      = {a["ID"] for a in artifacts}
    unknown_imp_tgts = sorted({lnk["Target_ID"] for lnk in imp_links
                                if lnk["Target_ID"] not in art_ids_all})
    if unknown_imp_tgts:
        print(f"  WARNING: IMP markers reference unknown requirement IDs: {unknown_imp_tgts}")

    # Sync stereotype labels from the LaTeX-generated vocab CSV (single source of truth).
    # Falls back to the built-in SYSML_REQTYPE_LABEL dict on the first run before
    # the CSV exists.  Later entries in the CSV override earlier ones, so user
    # \reqmanlabel calls in the .tex file take precedence over the package defaults.
    for row in vocab:
        name = row["Name"].strip()
        label = row["Label"].strip()
        if name and label:
            SYSML_REQTYPE_LABEL[name] = label

    # If the document declares types, use only those (defaults are a fallback for
    # documents that declare nothing).  This lets authors define the authoritative
    # set for their project and get flagged on anything outside it.
    type_descriptions = {}
    # Terminal type prefixes: artifacts of these types end the refinement chain
    # and are exempt from the unaccounted-artifacts check. Declared via the
    # optional 4th argument of \reqmantype ("terminal").
    terminal_prefixes = set()
    if type_rows:
        prefix_reqtype = {}
        for row in type_rows:
            p = row["Prefix"].strip()
            if p:
                prefix_reqtype[p]    = row["ReqType"].strip()
                type_descriptions[p] = row["Description"].strip()
                flags = {f for f in re.split(r"[;,\s]+", (row.get("Terminal") or "").strip()) if f}
                if "terminal" in flags:
                    terminal_prefixes.add(p)
                if flags - {"terminal"}:
                    print(f"  WARNING: unknown \\reqmantype flag(s) for {p}: "
                          f"{sorted(flags - {'terminal'})}")
    else:
        prefix_reqtype = dict(PREFIX_REQTYPE)

    # durable-cache.tex declares \reqmantype{IMP}{...}[terminal], so
    # type_rows already covers it on every normal run; this only matters on
    # the very first invocation of a fresh checkout, before any LaTeX pass
    # has produced types.csv yet, when the PREFIX_REQTYPE fallback above is
    # used instead and doesn't know about IMP.
    prefix_reqtype.setdefault("IMP", "requirement")

    # Split coverage.csv rows into \reqcover/\reqexpect obligations and
    # \reqterminal markers.
    obligations   = []
    terminal_reqs = {}
    for row in coverage:
        rel  = (row.get("Required_Rel") or "").strip()
        pfx  = (row.get("Required_Prefix") or "").strip()
        tid  = (row.get("Required_ID") or "").strip()
        note = (row.get("Note") or "").strip()
        if rel == "terminal":
            terminal_reqs[row["Source_ID"]] = note
        elif rel or pfx or tid:
            if tid and not pfx:
                pfx = tid.split("-")[0]
            obligations.append({"Source_ID": row["Source_ID"], "Rel": rel,
                                 "Prefix": pfx, "Required_ID": tid, "Note": note})
    if terminal_reqs:
        print(f"  terminal-marked artifacts: {len(terminal_reqs)}")

    # Any artifact type not in the merged map is undeclared
    undeclared_types = {
        a["Type"] for a in artifacts if a["Type"] not in prefix_reqtype
    }
    if undeclared_types:
        print(f"  undeclared types: {sorted(undeclared_types)}")

    # Map each requirement ID to its defining source file:line (for the json
    # source pointer), scanning the .tex sources but not the generated outdir.
    source_index = build_source_index(os.getcwd(), skip_dirs=[outdir])
    print(f"  source-indexed requirements: {len(source_index)}")

    generate_tracing_report(outdir, jobname, artifacts, links, obligations, prefix_reqtype,
                            type_descriptions, undeclared_types, terminal_prefixes,
                            terminal_reqs, ext_links)
    generate_requirements_json(outdir, jobname, artifacts, links, obligations,
                               prefix_reqtype, undeclared_types, terminal_prefixes,
                               terminal_reqs, source_index, ext_links)
    generate_types_json(jobname, prefix_reqtype, type_descriptions, terminal_prefixes)
    generate_reqtables(outdir, jobname, artifacts, links, obligations, ext_links,
                       prefix_reqtype, terminal_reqs)
    generate_coverage_report(outdir, jobname, artifacts, links)

    if unknown_macros_seen:
        print(f"  strip_latex: unknown macros encountered (unwrapped to inner text): "
              f"{sorted(unknown_macros_seen)}")

    partial_requests = load_csv(f"{outdir}/{jobname}-partial-diagrams.csv")
    if partial_requests:
        print(f"  partial diagrams: {len(partial_requests)}")

    art_by_id = {a["ID"]: a for a in artifacts}
    for req in partial_requests:
        label          = req["Label"].strip()
        ids            = req["IDs"].strip()
        if not ids:
            focus_ids  = set(art_by_id)
        else:
            focus_ids  = {rid.strip() for rid in ids.split(";") if rid.strip()}
        show_neighbors = req["ShowNeighbors"].strip().lower() == "true"

        # Determine neighbours from the links CSV (not from the global layout)
        neighbor_ids = set()
        if show_neighbors:
            for lnk in links:
                src_focus = lnk["Source_ID"] in focus_ids
                tgt_focus = lnk["Target_ID"] in focus_ids
                if src_focus and not tgt_focus and lnk["Target_ID"] in art_by_id:
                    neighbor_ids.add(lnk["Target_ID"])
                if tgt_focus and not src_focus and lnk["Source_ID"] in art_by_id:
                    neighbor_ids.add(lnk["Source_ID"])

        try:
            max_per_part = int((req.get("MaxPerPart") or "0").strip() or "0")
        except ValueError:
            max_per_part = 0

        # Clear any stale per-part tikz from a previous run so that a shrinking
        # (or removed) partition never leaves orphaned parts behind.
        for old in glob.glob(f"{outdir}/{jobname}-partial-{label}-p*-tikz.tikz"):
            os.remove(old)

        if ids and show_neighbors:
            # Local diagram of a focus artifact: star layout, split into parts
            # by row capacity (max_per_part is not needed for this layout).
            stale = f"{outdir}/{jobname}-partial-{label}-tikz.tikz"
            if os.path.exists(stale):
                os.remove(stale)
            for k, (part_layout, part_neighbors) in enumerate(
                    star_layout_parts(focus_ids, links, art_by_id), start=1):
                generate_tikz_diagram(outdir, jobname, artifacts, part_layout,
                                      neighbor_ids=part_neighbors, label=f"{label}-p{k}",
                                      label_pt=STAR_LABEL_PT)
            continue

        if max_per_part > 0 and neighbor_ids:
            # Partitioned mode: split the neighbours into deterministic chunks,
            # repeating the focus node(s) in every part so that every neighbour
            # is rendered in exactly one readable sub-diagram. Use the fewest
            # parts that keep each at or below max_per_part, then balance sizes
            # evenly so no part is left with a lone, oversized node (e.g. 9 with
            # cap 4 -> 3 parts of 3, not 4+4+1).
            ordered   = sorted(neighbor_ids)
            n         = len(ordered)
            nparts    = -(-n // max_per_part)        # ceil(n / max_per_part)
            base, rem = divmod(n, nparts)            # spread the remainder
            chunks, start = [], 0
            for p in range(nparts):
                size = base + (1 if p < rem else 0)
                chunks.append(ordered[start:start + size])
                start += size
            for k, chunk in enumerate(chunks, start=1):
                part_label   = f"{label}-p{k}"
                part_include = focus_ids | set(chunk)
                part_dotpath = generate_layout_dot(outdir, jobname, artifacts, links,
                                                   included_ids=part_include, label=part_label)
                part_layout  = parse_dot_plain(part_dotpath)
                if not (part_layout and part_layout["nodes"]):
                    print(f"  WARNING: layout failed for partial diagram '{part_label}'")
                    continue
                generate_tikz_diagram(outdir, jobname, artifacts, part_layout,
                                      neighbor_ids=set(chunk), label=part_label)
            continue

        included_ids = focus_ids | neighbor_ids

        # Generate a dedicated layout DOT for just the included nodes so that
        # DOT produces a tight arrangement rather than a cut-out of the global graph.
        partial_dotpath = generate_layout_dot(outdir, jobname, artifacts, links,
                                              included_ids=included_ids, label=label)
        partial_layout  = parse_dot_plain(partial_dotpath)
        if not (partial_layout and partial_layout["nodes"]):
            print(f"  WARNING: layout failed for partial diagram '{label}'")
            continue

        generate_tikz_diagram(outdir, jobname, artifacts, partial_layout,
                              neighbor_ids=neighbor_ids, label=label)

    generate_overview_diagram(outdir, jobname, artifacts, links, list(prefix_reqtype),
                              terminal_prefixes)


if __name__ == "__main__":
    main()
